#define TEX_W 128
#define TEX_H 64

static C3D_Tex s_tex;
static Tex3DS_SubTexture s_sub[95];

static int morton(int x, int y)
{
	return (x & 1) | ((y & 1) << 1) | ((x & 2) << 1) | ((y & 2) << 2) | ((x & 4) << 2) | ((y & 4) << 3);
}

bool fontInit(void)
{
	if (!C3D_TexInit(&s_tex, TEX_W, TEX_H, GPU_RGBA4)) return false;
	uint16_t* px = s_tex.data;
	memset(px, 0, TEX_W * TEX_H * 2);
	for (int g = 0; g < 95; g++) {
		int cx = (g % 16) * 8, cy = (g / 16) * 8;
		for (int y = 0; y < 7; y++)
			for (int x = 0; x < 5; x++) {
				if (!(s_glyphs[g][y] & (0x10 >> x))) continue;
				int X = cx + x, Y = cy + y;

				px[((Y / 8) * (TEX_W / 8) + X / 8) * 64 + morton(X % 8, Y % 8)] = 0xFFFF;
			}
		Tex3DS_SubTexture* s = &s_sub[g];
		s->width = 6;
		s->height = 8;
		s->left = (float)cx / TEX_W;
		s->right = (float)(cx + 6) / TEX_W;
		s->top = 1.0f - (float)cy / TEX_H;
		s->bottom = 1.0f - (float)(cy + 8) / TEX_H;
	}
	C3D_TexFlush(&s_tex);
	C3D_TexSetFilter(&s_tex, GPU_NEAREST, GPU_NEAREST);
	return true;
}

void fontExit(void) { C3D_TexDelete(&s_tex); }

static float drawWord(const char* s, int n, float x, float y, float scale, u32 color)
{
	C2D_ImageTint tint;
	C2D_PlainImageTint(&tint, color, 1.0f);
	for (int i = 0; i < n; i++) {
		unsigned char c = (unsigned char)s[i];
		if (c >= 32 && c <= 126 && c != ' ') {
			C2D_Image img = { &s_tex, &s_sub[c - 32] };
			C2D_DrawImageAt(img, x, y, 0.5f, &tint, scale, scale);
		}
		x += FONT_ADVANCE * scale;
	}
	return x;
}

float fontDraw(const char* s, float x, float y, float scale, u32 color, float wrap)
{
	float lineX = x, cy = y;
	const char* p = s;
	while (*p) {
		if (*p == '\n') {
			lineX = x;
			cy += FONT_LINE * scale;
			p++;
			continue;
		}
		const char* e = p;
		while (*e && *e != ' ' && *e != '\n') e++;
		int n = (int)(e - p);
		float w = n * FONT_ADVANCE * scale;
		if (wrap > 0 && lineX > x && lineX + w > x + wrap) {
			lineX = x;
			cy += FONT_LINE * scale;
		}
		lineX = drawWord(p, n, lineX, cy, scale, color);
		p = e;
		if (*p == ' ') {
			lineX += FONT_ADVANCE * scale;
			p++;
		}
	}
	return cy + FONT_LINE * scale;
}

float fontWidth(const char* s, float scale) { return strlen(s) * FONT_ADVANCE * scale; }
